"""
Build pokemon_z_team_training.apworld.

  python make_apworld.py "<clean Pokemon FireRed (USA) 1.0 .gba>"

Steps: transplant -> plan + regenerated extracted_data -> verify the runtime path from a clean ROM
reproduces the same ROM -> zip the world.
"""
import json
import os
import sys
import zipfile

import bsdiff4

from core import Ctx
from paths import WORLD, DIST, BUILD, HACK_BPS, AP_BASE_PATCH, UPSTREAM_DATA, UPSTREAM_WORLD, FINAL_BASE_ROM
from regen import regen
from transplant import Transplanter

sys.path.insert(0, WORLD)
from zt_patch import apply_bps, apply_plan  # noqa: E402  (the world's own runtime code)

vanilla_path = sys.argv[1]
ctx = Ctx(vanilla_path, HACK_BPS, AP_BASE_PATCH)
upstream = json.load(open(UPSTREAM_DATA, encoding="utf-8-sig"))
t = Transplanter(ctx)
t.pass_inplace()
t.pass_species()
t.pass_moves(upstream["damage_type_table"])
t.pass_trainers()
t.pass_items()
t.pass_graphics()
t.pass_tilesets()
t.pass_maps()
t.pass_anims()
t.pass_battle_scripts()
t.pass_audio()
t.pass_code()
t.pass_finalize()

plan_path = os.path.join(WORLD, "data", "ztt_plan.bin")
ctx.save_plan(plan_path)
final_base = bytes(ctx.A)

# --- regenerate the ROM-dependent generation data ---
ed, report = regen(upstream, final_base)
ed["rom_checksum"] = t.checksum
ed["rom_names"] = {k: "pokemon z team training AP" for k in ed["rom_names"]}
ed["comment"] = ("Generated by tools/make_apworld.py from the Archipelago FireRed base ROM with "
                 "Pokemon Z Team Training transplanted. Do not edit by hand.")
with open(os.path.join(WORLD, "data", "extracted_data.json"), "w", encoding="utf-8") as f:
    json.dump(ed, f, separators=(",", ":"), sort_keys=True)
from species_rename import build_map, apply as apply_species_names, build_item_map, apply_items  # noqa: E402
species_map = build_map(ctx, final_base, UPSTREAM_WORLD, ed)
dex_locations_renamed = apply_species_names(WORLD, UPSTREAM_WORLD, species_map)
item_map = build_item_map(ctx, final_base, UPSTREAM_WORLD, ed)
apply_items(WORLD, UPSTREAM_WORLD, item_map)
import place_rename  # noqa: E402
name_log = []
name_maps = place_rename.build(ctx, final_base, ed, species_map)
loc_map = place_rename.location_map(WORLD, name_maps, name_log)
loc_files = place_rename.apply(WORLD, loc_map, "locations.json")
ap_item_map = place_rename.item_map(WORLD, name_maps)
item_files = place_rename.apply(WORLD, ap_item_map, "items.json")
from evolutions import rebuild as rebuild_evolutions  # noqa: E402
evo_report = rebuild_evolutions(WORLD, ed, UPSTREAM_WORLD, species_map)

# --- verify the runtime path a player's client will take ---
vanilla = open(vanilla_path, "rb").read()
hack = apply_bps(vanilla, open(HACK_BPS, "rb").read())
base = bsdiff4.patch(vanilla, open(os.path.join(WORLD, "data", "base_patch_firered.bsdiff4"), "rb").read())
rebuilt = apply_plan(base, hack, open(plan_path, "rb").read())
assert rebuilt == final_base, "runtime path does not reproduce the build"
os.makedirs(BUILD, exist_ok=True)
open(FINAL_BASE_ROM, "wb").write(final_base)

# --- package ---
os.makedirs(DIST, exist_ok=True)
out = os.path.join(DIST, "pokemon_z_team_training.apworld")
with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as z:
    for root, dirs, files in os.walk(WORLD):
        dirs[:] = [d for d in dirs if d != "__pycache__"]
        for fn in files:
            full = os.path.join(root, fn)
            rel = os.path.relpath(full, os.path.dirname(WORLD))
            z.write(full, rel.replace(os.sep, "/"))

print("plan ops:", len(ctx.plan), " free space used up to", hex(ctx.alloc_ptr))
for k, v in sorted(t.stats.items()):
    print("  %-34s %d" % (k, v))
print("regenerated:", report)
print("evolutions:", evo_report)
print("locations renamed:", len(loc_map), "in", loc_files, " AP items renamed:", len(ap_item_map), "in", item_files)
for line in name_log:
    print("  name:", line)
print("species renamed:", len(species_map), " dexsanity locations renamed:", dex_locations_renamed,
      " items renamed:", len(item_map))
print("maps:", {k: v for k, v in sorted(t.stats.items()) if k.startswith(("maps_", "map_", "general_"))})
print("checksum:", hex(t.checksum))
print("log:")
for line in ctx.log:
    if "sItemIconTable[" not in line:
        print("  ", line)
print("wrote", out, os.path.getsize(out), "bytes")
